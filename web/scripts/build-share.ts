// The second half of `npm run build:share`: puts the built script and stylesheet into one HTML file, the
// share viewer template, with the Content-Security-Policy that pins both by hash (src/share/csp.ts) and a
// placeholder where the sender puts the age-encrypted note. Deterministic: the same sources give the same bytes.
//
//   node scripts/build-share.ts [OUT.html] [--swift Sources/SempereShareViewer/ShareViewerTemplate.swift]
//
// `--swift` also writes the template as a Swift source (the CLI and the app embed it; scripts/build-share-template.sh).

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { shareContentSecurityPolicy } from "../src/share/csp.ts";

/** Where the sender's data goes; `sempere share --verify` treats the file as equal to the template with this put back. */
export const dataPlaceholder = "@@SEMPERE-SHARE-DATA@@";

const dist = join(import.meta.dirname, "..", "dist-share");
// A raw control character (a library's `\x7f` in a template literal) is written as its escape: legal in every
// JavaScript string, template and regular expression, and the Swift source that embeds this page refuses raw ones.
// eslint-disable-next-line no-control-regex
const js = readFileSync(join(dist, "share.js"), "utf8").trimEnd().replace(/[\x00-\x08\x0b-\x1f\x7f]/g, (c) => `\\x${c.charCodeAt(0).toString(16).padStart(2, "0")}`);
const css = readFileSync(join(dist, "share.css"), "utf8").trimEnd();

// Text inside <script> and <style> ends at these; the build must never produce them.
for (const [name, text, bad] of [["script", js, /<\/script|<!--/i], ["style", css, /<\/style|<!--/i]] as const) {
  if (bad.test(text)) throw new Error(`the ${name} contains markup that would end its element`);
}

const sha = (s: string): string => createHash("sha256").update(s, "utf8").digest("base64");
const csp = shareContentSecurityPolicy(sha(js), sha(css));

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="${csp}">
<meta name="referrer" content="no-referrer">
<meta name="color-scheme" content="light dark">
<meta name="generator" content="sempere-share/1">
<title>Shared note</title>
<link rel="icon" href="data:,">
<style>${css}</style>
</head>
<body>
<div id="app"><noscript>Open this file in a web browser to read the note. / Abre este archivo en un navegador web para leer la nota.</noscript></div>
<script type="text/plain" id="share-data" data-format="sempere-share/1">${dataPlaceholder}</script>
<script>${js}</script>
</body>
</html>
`;

const args = process.argv.slice(2);
const swiftAt = args.indexOf("--swift");
const swiftOut = swiftAt >= 0 ? args[swiftAt + 1] : undefined;
const positional = args.filter((a, i) => a !== "--swift" && i !== swiftAt + 1);
const out = positional[0] ?? join(dist, "share-viewer.html");
writeFileSync(out, html);
if (swiftOut) {
  if (html.includes('"""#####')) throw new Error("the template contains the end of its Swift string");
  writeFileSync(swiftOut, `// Generated by scripts/build-share-template.sh from web/ (npm run build:share). Do not edit: the \`web\` CI job
// rebuilds it and fails on a difference. docs/web-viewer.md "Share files" lists the hashes of each release's.

/// The share viewer page (docs/design/1.3-share.md §3.3): the web viewer's note view, one script and one stylesheet,
/// with the Content-Security-Policy that pins both and a placeholder where \`WebPageShare\` puts the encrypted note.
public enum ShareViewerTemplate {
    /// The page, UTF-8.
    public static let html: String = #####"""
${html}"""#####

    /// \`html\` as bytes.
    public static var data: [UInt8] { Array(html.utf8) }
}
`);
}
console.log(`${out}: ${html.length} bytes, script sha256-${sha(js)}, style sha256-${sha(css)}`);
