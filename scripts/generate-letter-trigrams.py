#!/usr/bin/env python3
"""Generates Sources/Sempere/LetterTrigrams.swift: how English-like a run of
letters is, for `PassphraseStrength` (a run that reads like words is priced as
dictionary words, one that does not as random letters).

Usage: python3 scripts/generate-letter-trigrams.py [WORDS]
WORDS defaults to /usr/share/dict/words (macOS and FreeBSD ship Webster's
Second International, 1934, whose copyright has lapsed). Only lowercase ASCII
words are used, each once (word types, not frequencies). The generated table
holds statistics derived from the list, not the list.

The table: for every context of two characters (`^` = start of the run, then
a-z) and every next character (a-z, then `$` = end of the run), the cost in
half bits, -2·log2 P(next | context) with add-0.3 smoothing, capped at 30
(15 bits). Context (a, b) and next c are at index (a·27 + b)·27 + c, with
`^` = 0 and a-z = 1...26 in contexts, a-z = 0...25 and `$` = 26 as the next
character. One character per entry, `chr(48 + cost)`, in one string literal
(CI type-checks large array literals slowly).
"""
import math
import os
import sys
from collections import Counter

WORDS = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/dict/words"
OUT = os.path.join(os.path.dirname(__file__), "..", "Sources", "Sempere", "LetterTrigrams.swift")
SMOOTHING = 0.3
CAP = 30

words = set()
with open(WORDS, encoding="utf-8") as f:
    for line in f:
        w = line.strip().lower()
        if w.isascii() and w.isalpha():
            words.add(w)

counts, totals = Counter(), Counter()
for w in sorted(words):
    s = "^^" + w + "$"
    for a, b, c in zip(s, s[1:], s[2:]):
        counts[a, b, c] += 1
        totals[a, b] += 1

context = "^abcdefghijklmnopqrstuvwxyz"
following = "abcdefghijklmnopqrstuvwxyz$"
cells = []
for a in context:
    for b in context:
        for c in following:
            p = (counts[a, b, c] + SMOOTHING) / (totals[a, b] + SMOOTHING * len(following))
            cells.append(chr(48 + min(CAP, round(-2 * math.log2(p)))))
table = "".join(cells)
lines = [table[i:i + 108] for i in range(0, len(table), 108)]

with open(OUT, "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/generate-letter-trigrams.py from %d words; do not edit.\n" % len(words))
    f.write("// Letter trigram costs for PassphraseStrength (see the script for the layout).\n\n")
    f.write("enum LetterTrigrams {\n")
    f.write("    /// One character per (context, next) cell: cost in half bits = scalar value - 48.\n")
    f.write("    static let encoded = \"\"\"\n")
    for k, line in enumerate(lines):
        f.write("        " + line + ("\\\n" if k + 1 < len(lines) else "\n"))
    f.write("        \"\"\"\n}\n")
print("wrote", OUT, len(table), "cells")
